export const TASK_SITES = { riverbank, carewell, brightline };

export function render() {
  const out = {};
  for (const [site, pages] of Object.entries(TASK_SITES)) {
    for (const [file, html] of Object.entries(pages)) out[`${site}/${file}`] = html;
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [rel, html] of Object.entries(render())) {
    const file = join(HERE, rel);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, html);
  }
}
