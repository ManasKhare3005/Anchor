import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { LABELS_DIR, allLabels, loadLabels, saveLabels, type Label } from "./labels.ts";
import { SHOPPING_FEATURES, parseArchived, propose } from "./propose.ts";
import { BENCH_DIR, cachePath, cachedFor, loadRealSites } from "./wayback.ts";

/**
 * npm run real:propose — propose labels for every cached site (never overwrites a label that is
 * already confirmed or rejected) and rewrite docs/benchmark-labels-review.md.
 */
mkdirSync(LABELS_DIR, { recursive: true });
const skipped: string[] = [];

for (const site of loadRealSites()) {
  const before = cachedFor(site.id, "before");
  const after = cachedFor(site.id, "after");
  if (!before || !after) {
    skipped.push(
      `${site.name}: archived ${!before ? "before" : "after"} page keeps failing to download`,
    );
    continue;
  }
  const docBefore = parseArchived(readFileSync(cachePath(site.id, before), "utf8"), site.url);
  const docAfter = parseArchived(readFileSync(cachePath(site.id, after), "utf8"), site.url);
  const existing = loadLabels(site.id);
  const features: Label[] = SHOPPING_FEATURES.map((rule) => {
    const kept = existing?.features.find((f) => f.id === rule.id && f.status !== "proposed");
    if (kept && existing?.before === before && existing.after === after) return kept;
    const onBefore = propose(docBefore, rule, site.url);
    return {
      id: rule.id,
      label: rule.label,
      before: onBefore,
      after: propose(docAfter, rule, site.url, onBefore),
      status: "proposed",
    };
  });
  saveLabels({
    site: site.id,
    url: site.url,
    category: site.category,
    before,
    after,
    features,
  });
}

// Review sheet
const checkFile = join(BENCH_DIR, "claude-check.json");
const check: Record<string, [string, string]> = existsSync(checkFile)
  ? (JSON.parse(readFileSync(checkFile, "utf8")) as Record<string, [string, string]>)
  : {};
const fmtDate = (ts: string) => `${ts.slice(0, 4)}-${ts.slice(4, 6)}-${ts.slice(6, 8)}`;
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ");
const spot = (s: Label["before"]) =>
  s
    ? `**${cell(s.text || "(no text)")}**<br>\`${cell(s.href || "-")}\`<br>${s.region}`
    : "_not found_";

const lines: string[] = [
  "# Benchmark labels — review",
  "",
  "Generated by `npm run real:propose`. For each site and feature: where the proposer thinks the feature is on the archived page **before** and **after**. Labels only count once confirmed.",
  "",
  '**How to review:** I\'ve pre-checked every row ("Claude\'s check"). Rows marked *ok* become labels; rows marked *exclude* are left out. Reply **"agree"** if that\'s fine, or name the rows you\'d change (e.g. "amazon-1 exclude", "macys-4 ok"). The before/after links open the archived pages if you want to look.',
  "",
  'Why some rows are excluded: archived pages are the original HTML with no scripts run, so a button a site draws with scripts can look "missing" when it isn\'t. A missing "after" only counts as a real removal if you confirm it.',
  "",
  "Archived pages: Wayback Machine, original HTML (no scripts run). Public home pages only.",
  "",
];
if (skipped.length) {
  lines.push(
    "**Sites without a usable archive (excluded for now):**",
    "",
    ...skipped.map((s) => `- ${s}`),
    "",
  );
}
for (const l of allLabels()) {
  lines.push(
    `## ${l.site} — ${l.url}`,
    "",
    `Before: [${fmtDate(l.before)}](https://web.archive.org/web/${l.before}/${l.url}) · After: [${fmtDate(l.after)}](https://web.archive.org/web/${l.after}/${l.url}) (archived copies; open to check)`,
    "",
    "| # | Feature | Before | After | Claude's check | Status |",
    "| --- | --- | --- | --- | --- | --- |",
    ...l.features.map((f, i) => {
      const [verdict, why] = check[`${l.site}-${f.id}`] ?? (f.before ? ["?", ""] : ["skip", ""]);
      const shown =
        verdict === "skip"
          ? "skipped (not on before page)"
          : `${verdict}${why ? `: ${cell(why)}` : ""}`;
      return `| ${l.site}-${i + 1} | ${f.label} | ${spot(f.before)} | ${spot(f.after)} | ${shown} | ${f.status} |`;
    }),
    "",
  );
}
writeFileSync(join(BENCH_DIR, "..", "docs", "benchmark-labels-review.md"), lines.join("\n"));
console.log(`labels written for ${allLabels().length} sites; skipped ${skipped.length}`);
